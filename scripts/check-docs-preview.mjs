import assert from 'node:assert/strict'
import { mkdirSync, readFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
const [url, executablePath, playwrightEntry] = process.argv.slice(2)
const { chromium } = await import(pathToFileURL(playwrightEntry).href)
mkdirSync('.local-preview', { recursive: true })
const browser = await chromium.launch({ executablePath, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
try {
  await page.goto(`${url}/#docs`)
  await page.locator('.docs-project-card').waitFor()
  assert.equal(await page.title(), 'Docs · RF Agent Lab')
  assert.deepEqual(await page.locator('.nav-links button').evaluateAll((buttons) => buttons.map((button) => button.getAttribute('aria-label'))), ['Go to mcp', 'Go to cases', 'Go to skills', 'Go to demos', 'Go to docs'])
  assert.equal(await page.locator('.docs-project-card').count(), 1)
  assert.equal(await page.locator('.article-row').count(), 0)
  assert.equal(await page.locator('#docs h1').innerText(), 'Docs')
  assert.equal(await page.locator('#docs .section-heading').count(), 0)
  for (const width of [1440, 834, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('button', { name: 'Go to skills', exact: true }).click()
    const skill = await page.locator('#skills .skill-card').boundingBox()
    await page.getByRole('button', { name: 'Go to docs', exact: true }).click()
    await page.locator('.docs-project-card').waitFor()
    const layout = await page.locator('.docs-project-card').evaluate((el) => ({ card: el.getBoundingClientRect().width, grid: el.parentElement.getBoundingClientRect().width, left: el.getBoundingClientRect().left, gridLeft: el.parentElement.getBoundingClientRect().left }))
    assert(Math.abs(layout.left - layout.gridLeft) < 1, 'Docs must occupy the left column')
    assert(width > 760 ? layout.card < layout.grid * .55 : Math.abs(layout.card - layout.grid) < 2, `Docs column count at ${width}`)
    assert(Math.abs(layout.card - skill.width) < 2, `Docs and Skills card widths must match at ${width}`)
    if (width === 1440) assert(Math.abs((await page.locator('.docs-project-card').boundingBox()).height - skill.height) < 2, 'Desktop card heights must match')
    assert.equal(await page.locator('.docs-card-facts').count(), 0)
    assert(await page.locator('.docs-project-card').evaluate((el) => el.scrollWidth <= el.clientWidth), `Docs card overflow at ${width}`)
    await page.screenshot({ path: `.local-preview/docs-two-column-${width}.png` })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '.local-preview/docs-directory-desktop.png' })
  await page.getByLabel('搜索技术文档').fill('missing-example')
  assert.equal(await page.locator('.docs-project-card').count(), 0)
  await page.getByLabel('搜索技术文档').fill('PyAEDT')
  await page.locator('.docs-project-card').click()
  await page.locator('.docs-markdown').waitFor()
  const originalManual = readFileSync('docs/pyaedt-postprocessing/README.md', 'utf8')
  assert.equal(await page.locator('.docs-code').count(), (originalManual.match(/^```/gm) ?? []).length / 2)
  assert.equal(await page.locator('.docs-table-scroll table').count(), (originalManual.match(/^\| ---/gm) ?? []).length)
  assert.match(await page.locator('.docs-markdown').innerText(), /未连接 AEDT/)
  assert(!/\*\*接口核对/.test(await page.locator('.docs-markdown').innerText()))
  assert.equal(await page.locator('a[href="https://pypi.org/project/pyaedt/1.9.0/"]').first().getAttribute('target'), '_blank')
  await page.screenshot({ path: '.local-preview/docs-manual-desktop.png' })
  await page.locator('.docs-toc a').filter({ hasText: '13. 已发现的接口陷阱' }).click()
  await page.waitForFunction(() => location.hash.includes('section=') && document.getElementById('doc-13-已发现的接口陷阱')?.getBoundingClientRect().top < 140)
  assert(await page.locator('#docs').evaluate((el) => el.scrollTop > 1000))
  await page.locator('.docs-markdown a').filter({ hasText: 'VALIDATION.md' }).first().click()
  await page.waitForFunction(() => document.querySelector('.docs-file-bar span')?.textContent === 'VALIDATION.md')
  assert(!/E:\\codexProj/.test(await page.locator('.docs-markdown').innerText()))
  await page.reload()
  await page.locator('.docs-file-bar').waitFor()
  assert.equal(await page.locator('.docs-file-bar span').innerText(), 'VALIDATION.md')
  await page.goBack()
  await page.waitForFunction(() => document.querySelector('.docs-file-bar span')?.textContent === 'README.md')
  await page.goForward()
  await page.waitForFunction(() => document.querySelector('.docs-file-bar span')?.textContent === 'VALIDATION.md')
  for (const name of ['README.md', 'api_snapshot.md', 'VALIDATION.md', 'post_helpers.py', 'verify_offline.py', 'refresh_api_snapshot.py', 'compare_official_docs.py', 'api_snapshot.json', 'official_doc_check.json']) {
    await page.getByRole('navigation', { name: '文档集合文件' }).getByRole('link').filter({ has: page.locator('small', { hasText: new RegExp(`^${name.replaceAll('.', '\\.')}$`) }) }).click()
    await page.waitForFunction((filename) => document.querySelector('.docs-file-bar span')?.textContent === filename, name)
    const text = await page.locator('.docs-markdown').innerText()
    assert(!text.includes('Cai_HFSS') && !text.includes('E:\\codexProj\\Github_Personal_Page'), `${name}: local environment path leaked`)
  }
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载当前文件' }).click()
  const download = await downloadPromise
  assert.equal(download.suggestedFilename(), 'official_doc_check.json')
  const downloaded = JSON.parse(readFileSync(await download.path(), 'utf8'))
  assert.equal(downloaded.checks.length, 27)
  assert.equal(downloaded.package_entry, '[local environment path omitted]')
  await page.getByRole('navigation', { name: '文档集合文件' }).getByRole('link', { name: '后处理辅助函数 post_helpers.py' }).click()
  await page.getByRole('button', { name: '复制代码', exact: true }).click()
  await page.getByRole('button', { name: '复制代码', exact: true }).getByText('已复制').waitFor()
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /def checked_call/)
  await page.goto(`${url}/#/docs/pyaedt-postprocessing`)
  await page.locator('.docs-markdown').waitFor()
  for (const [width, height] of [[834, 1112], [390, 844], [320, 740]]) {
    await page.setViewportSize({ width, height })
    await page.locator('#docs').evaluate((el) => el.scrollTo(0, 0))
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Document overflow at ${width}`)
    assert(await page.locator('#docs').evaluate((el) => el.scrollWidth <= el.clientWidth), `Docs panel overflow at ${width}`)
    await page.screenshot({ path: `.local-preview/docs-manual-${width}.png` })
    await page.getByRole('link', { name: '← Back to Docs', exact: true }).click()
    await page.locator('.docs-project-card').waitFor()
    assert(await page.locator('.docs-project-card').evaluate((el) => el.scrollWidth <= el.clientWidth), `Docs card overflow at ${width}`)
    await page.screenshot({ path: `.local-preview/docs-directory-${width}.png` })
    await page.locator('.docs-project-card').click()
    await page.locator('.docs-markdown').waitFor()
  }
  await page.goto(`${url}/#/docs/hfss-automation-boundaries`)
  await page.locator('.docs-not-found').waitFor()
  await page.goto(`${url}/#/docs/pyaedt-postprocessing?file=unknown.py`)
  await page.locator('.docs-not-found').waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: one real Docs card, search, markdown tables/code, TOC, nine files, clipboard, downloads, refresh, hidden placeholders and responsive layout')
} finally { await browser.close() }
