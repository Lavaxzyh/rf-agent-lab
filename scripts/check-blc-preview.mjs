import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, mkdirSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
const [url, executablePath, playwrightEntry] = process.argv.slice(2)
const { chromium } = await import(pathToFileURL(playwrightEntry).href)
const data = JSON.parse(readFileSync('src/data/blc-baseline.json', 'utf8'))
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex')
mkdirSync('.local-preview', { recursive: true })
assert.deepEqual(readdirSync('public/models/blc-baseline').sort(), ['blc_baseline.aedt', 'parameters.json'])
const browser = await chromium.launch({ executablePath, headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' })
const page = await context.newPage(), errors = []
page.on('pageerror', (error) => errors.push(error.message))
const settle = () => page.evaluate(async () => { for (let i = 0; i < 8; i++) await new Promise(requestAnimationFrame) })
try {
  await page.goto(`${url}/#cases`)
  await page.locator('.blc-gallery-card').waitFor()
  assert.equal(await page.locator('.case-feature').count(), 2)
  assert.deepEqual(await page.locator('.case-feature-copy h3').allTextContents(), ['二维码网格贴片天线', '单节 3 dB 分支线耦合器'])
  assert.equal(await page.locator('.case-feature-copy .case-badges span').count(), 6)
  assert.equal(await page.locator('.case-feature-copy > :not(h3):not(.case-badges)').count(), 0, 'Card summaries show only names and bubble tags')
  assert.equal(await page.locator('.case-list-heading, .case-list-foot').count(), 0)
  for (const [width, height] of [[1440, 1050], [834, 1112], [390, 844], [320, 740]]) {
    await page.setViewportSize({ width, height })
    await page.locator('#cases').evaluate((el) => el.scrollTo(0, 0))
    const gap = await page.evaluate(() => document.querySelector('.case-gallery-grid').getBoundingClientRect().top - document.querySelector('.topbar').getBoundingClientRect().bottom)
    assert(gap >= 18 && gap <= 30, `Gallery should start immediately below navigation at ${width}: gap ${gap}`)
    const cards = await page.locator('.case-gallery-grid .case-feature').evaluateAll((items) => items.map((item) => {
      const box = item.getBoundingClientRect()
      return { x: box.x, y: box.y, width: box.width, height: box.height, scrollWidth: item.scrollWidth, clientWidth: item.clientWidth }
    }))
    if (width > 760) {
      assert(Math.abs(cards[0].y - cards[1].y) < 1, `Cards must share a row at ${width}`)
      assert(cards[1].x > cards[0].x + cards[0].width, `Two columns at ${width}`)
      assert(Math.abs(cards[0].height - cards[1].height) < 1, `Equal card heights at ${width}`)
    } else assert(cards[1].y >= cards[0].y + cards[0].height, `Single column at ${width}`)
    for (const card of cards) assert(card.scrollWidth <= card.clientWidth, `Card overflow at ${width}`)
    assert(await page.locator('#cases').evaluate((el) => el.scrollWidth <= el.clientWidth), `Gallery overflow at ${width}`)
    await page.locator('#cases').evaluate((el) => el.scrollTo(0, 0))
    await page.screenshot({ path: `.local-preview/case-gallery-${width}.png` })
  }
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.locator('.blc-gallery-card').scrollIntoViewIfNeeded()
  await page.screenshot({ path: '.local-preview/blc-gallery-desktop.png' })
  await page.locator('.blc-gallery-card').click()
  await page.locator('.blc-stage canvas').waitFor()
  assert.equal(await page.title(), '单节分支线耦合器 · baseline | RF Agent Lab')
  const copy = await page.locator('.blc-page').innerText()
  assert(!/wbranch_wider|wmain_narrower|RMSE|误差分析/.test(copy))
  assert.equal(await page.getByRole('button', { name: 'Auto rotate · OFF' }).getAttribute('aria-pressed'), 'false')
  await settle()
  await page.screenshot({ path: '.local-preview/blc-model-desktop.png' })
  const initial = await page.locator('.blc-stage canvas').screenshot()
  const canvasBox = await page.locator('.blc-stage canvas').boundingBox()
  await page.mouse.move(canvasBox.x + canvasBox.width / 2, canvasBox.y + canvasBox.height / 2)
  await page.mouse.down(); await page.mouse.move(canvasBox.x + canvasBox.width / 2 + 150, canvasBox.y + canvasBox.height / 2 - 60, { steps: 12 }); await page.mouse.up()
  await settle()
  assert.notEqual(hash(await page.locator('.blc-stage canvas').screenshot()), hash(initial), 'Dragging must change the actual rendered camera view')
  await page.getByRole('button', { name: '俯视', exact: true }).click()
  await page.getByLabel('分层展示', { exact: true }).check()
  await page.getByLabel('端口面', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Auto rotate · OFF' }).click()
  await page.getByRole('button', { name: '重置视角与显示 ↺', exact: true }).click()
  await settle()
  assert.equal(await page.locator('.blc-toggles input:checked').count(), 3)
  assert.equal(await page.getByRole('button', { name: 'Auto rotate · OFF' }).getAttribute('aria-pressed'), 'false')
  assert.equal(hash(await page.locator('.blc-stage canvas').screenshot()), hash(initial), 'Reset must restore the actual default camera and layers')
  await page.getByLabel('分层展示', { exact: true }).check()
  await settle()
  await page.screenshot({ path: '.local-preview/blc-model-exploded.png' })
  await page.getByRole('button', { name: '重置视角与显示 ↺', exact: true }).click()
  const link = page.getByRole('link', { name: '下载 baseline 工程' })
  const response = await context.request.get(new URL(await link.getAttribute('href'), page.url()).href)
  assert(response.ok())
  assert.equal(hash(await response.body()), data.download.sha256)
  const downloadPromise = page.waitForEvent('download')
  await link.click()
  const download = await downloadPromise
  assert.equal(download.suggestedFilename(), 'blc_baseline.aedt')
  assert.equal(hash(readFileSync(await download.path())), data.download.sha256)
  assert.equal(await page.locator('.blc-download a[download$=".aedt"]').count(), 1)
  const parameters = await context.request.get(new URL(await page.locator('.blc-parameters-link').getAttribute('href'), page.url()).href)
  assert.deepEqual(await parameters.json(), data)
  await page.reload(); await page.locator('.blc-stage canvas').waitFor()
  await page.getByRole('link', { name: '← Back to Case Studies', exact: true }).click()
  await page.locator('.blc-gallery-card').waitFor()
  await page.goBack(); await page.locator('.blc-stage canvas').waitFor()
  for (const [name, width, height] of [['tablet', 834, 1112], ['mobile', 390, 844], ['narrow', 320, 740]]) {
    await page.setViewportSize({ width, height }); await settle()
    await page.locator('#cases').evaluate((el) => el.scrollTo(0, 0))
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: document overflow`)
    assert(await page.locator('#cases').evaluate((el) => el.scrollWidth <= el.clientWidth), `${name}: panel overflow`)
    await page.screenshot({ path: `.local-preview/blc-${name}.png` })
    await page.locator('.blc-model').scrollIntoViewIfNeeded()
    await page.screenshot({ path: `.local-preview/blc-viewer-${name}.png` })
  }
  assert.deepEqual(errors, [])
  console.log('PASS: baseline-only gallery/model, real camera interaction/reset, layers, default rotation OFF, download integrity, refresh/history, responsive layout')
} finally { await browser.close() }

const fallbackBrowser = await chromium.launch({ executablePath, headless: true, args: ['--disable-webgl'] })
try {
  const fallbackPage = await fallbackBrowser.newPage({ viewport: { width: 390, height: 844 } })
  await fallbackPage.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (type, ...args) { return String(type).includes('webgl') ? null : original.call(this, type, ...args) }
  })
  await fallbackPage.goto(`${url}/#/cases/blc-baseline`)
  await fallbackPage.locator('.blc-fallback svg').waitFor()
  assert(await fallbackPage.getByRole('button', { name: '俯视', exact: true }).isDisabled())
  assert(await fallbackPage.getByRole('link', { name: '下载 baseline 工程' }).isVisible())
  assert(!(await fallbackPage.locator('.blc-fallback').innerText()).includes('验证通过'))
  await fallbackPage.screenshot({ path: '.local-preview/blc-webgl-fallback.png' })
  console.log('PASS: WebGL-unavailable fallback, model download still available')
} finally { await fallbackBrowser.close() }
